"""Generates src/text/unicode_case_tables.hpp from Python's unicodedata: what Inkling 2 Mini's pre-tokenizer (GPT-4o's
regex) needs beyond text/unicode_tables.hpp. Its words are [\\p{Lu}\\p{Lt}\\p{Lm}\\p{Lo}\\p{M}]*[\\p{Ll}\\p{Lm}\\p{Lo}\\p{M}]+ and
[\\p{Lu}\\p{Lt}\\p{Lm}\\p{Lo}\\p{M}]+[\\p{Ll}\\p{Lm}\\p{Lo}\\p{M}]*, so a letter needs to be told as upper-case (Lu, Lt), lower-case
(Ll) or caseless (Lm, Lo); marks are in both sets and come from the class table.

Usage: python3 -I tools/gen/gen_unicode_case.py > src/text/unicode_case_tables.hpp

The categories are Python's Unicode version (printed in the header); tools/ref/inkling/classes_check.py checks them
against Hugging Face's regex engine code point by code point.
"""

import sys
import unicodedata


def main():
    # 1: Lu or Lt, 2: Ll, 3: Lm or Lo
    def value(cp):
        if 0xD800 <= cp <= 0xDFFF:
            return 0
        c = unicodedata.category(chr(cp))
        return {"Lu": 1, "Lt": 1, "Ll": 2, "Lm": 3, "Lo": 3}.get(c, 0)

    rows, start, cur = [], 0, 0
    for cp in range(0x110000):
        v = value(cp)
        if v != cur:
            if cur:
                rows.append((start, cp - 1, cur))
            start, cur = cp, v
    if cur:
        rows.append((start, 0x10FFFF, cur))
    o = sys.stdout.write
    o("// Generated by tools/gen/gen_unicode_case.py from Python %s's unicodedata (Unicode %s). Do not edit.\n"
      % (sys.version.split()[0], unicodedata.unidata_version))
    o("#pragma once\n\n#include <cstdint>\n\nnamespace eklow::text::unicode {\n\n")
    o("// Runs of letters by case: 1 Lu or Lt, 2 Ll, 3 Lm or Lo (every other code point is in no run).\n")
    o("struct CaseRange { uint32_t lo, hi; uint8_t v; };\ninline constexpr CaseRange kCaseRanges[] = {\n")
    for i in range(0, len(rows), 4):
        o("    " + " ".join("{0x%X,0x%X,%d}," % r for r in rows[i:i + 4]) + "\n")
    o("};\n\n}  // namespace eklow::text::unicode\n")


if __name__ == "__main__":
    main()
